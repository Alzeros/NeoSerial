import assert from 'node:assert/strict';
import { withHeadlessBrowser } from './headless.mjs';

await withHeadlessBrowser(async ({ base, call, evaluate, until, click, fresh, delay }) => {
  await fresh('settings');
  await until('persistenceTest.calls.some(call => call.cmd === "show_settings_window")');
  await click('取消');
  await until('!document.querySelector("[data-tauri-drag-region]")');
  await evaluate(`persistenceTest.holdNext('get_settings'); persistenceTest.reopenSettings({section:'general',ext_module:null,anchor:null,request_id:101})`);
  await until('document.querySelector("[role=status]")?.textContent.includes("正在读取设置")');
  assert.equal(await evaluate('Boolean(persistenceTest.button("保存"))'), false);
  await until('document.body.innerText.includes("超时")', 8000);
  assert.equal(await evaluate('Boolean(persistenceTest.button("保存"))'), false);
  await until('persistenceTest.calls.some(call => call.cmd === "complete_settings_open" && call.args.requestId === 101 && call.args.error?.includes("超时"))');
  await click('重试');
  await until('Boolean(persistenceTest.button("保存"))', 2000);
  await evaluate(`persistenceTest.reopenSettings({section:'extensions',ext_module:'mcp',anchor:null,request_id:102})`);
  await until('document.body.innerText.includes("返回扩展") && document.body.innerText.includes("MCP 服务")', 2000);
  await until('persistenceTest.calls.some(call => call.cmd === "complete_settings_open" && call.args.requestId === 102 && call.args.error === null)');
  await evaluate('persistenceTest.release()');
  await delay(100);
  assert.ok(await evaluate('document.body.innerText.includes("返回扩展") && document.body.innerText.includes("MCP 服务")'), 'late IPC must not replace the latest navigation');
  await click('取消');
  await until('!document.querySelector("[data-tauri-drag-region]")');
  await evaluate(`persistenceTest.failNext('get_settings'); persistenceTest.reopenSettings({section:'appearance',ext_module:null,anchor:null,request_id:103})`);
  await until('document.body.innerText.includes("读取设置失败")');
  await until('persistenceTest.calls.some(call => call.cmd === "complete_settings_open" && call.args.requestId === 103 && call.args.error)');
  await click('重试');
  await until('Boolean(persistenceTest.button("保存"))');
  await click('雾灰松');
  await evaluate(`persistenceTest.reopenSettings({section:'general',ext_module:null,anchor:null,request_id:104})`);
  await until('persistenceTest.calls.some(call => call.cmd === "complete_settings_open" && call.args.requestId === 104 && call.args.error === null)');
  assert.equal(await evaluate('persistenceTest.button("应用").disabled'), false, 'a visible draft survives another open request');
  await evaluate(`persistenceTest.holdNext('plugin:window|hide')`);
  await click('取消');
  await evaluate(`persistenceTest.reopenSettings({section:'appearance',ext_module:null,anchor:null,request_id:105})`);
  await until('persistenceTest.calls.some(call => call.cmd === "complete_settings_open" && call.args.requestId === 105 && call.args.error === null)', 5000);
  await evaluate('persistenceTest.release()');
  await delay(100);
  assert.ok(await evaluate('Boolean(persistenceTest.button("保存"))'), 'a late hide response must not clear a reopened page');
  await click('取消');
  await until('!document.querySelector("[data-tauri-drag-region]")');
  await evaluate(`persistenceTest.holdNext('get_settings'); persistenceTest.reopenSettings({section:'general',ext_module:null,anchor:null,request_id:106})`);
  await until('document.querySelector("[role=status]")?.textContent.includes("正在读取设置")');
  await click('关闭');
  await until('!document.querySelector("[data-tauri-drag-region]")');
  await evaluate('persistenceTest.release()');
  await until('persistenceTest.calls.some(call => call.cmd === "complete_settings_open" && call.args.requestId === 106 && call.args.cancelled === true && call.args.error === null)');
  assert.equal(await evaluate('Boolean(persistenceTest.button("保存"))'), false, 'cancelled loading must not reopen the window');
  await call('Page.navigate', { url: `${base}/tests/browser/persistence-regressions.html?window=settings&run=pending-retry&extModule=mcp&requestId=200&failPending=1` });
  await until('window.persistenceTest?.run === "pending-retry"', 30000);
  await until('document.body.innerText.includes("打开设置失败")');
  await click('重试');
  await until('document.body.innerText.includes("返回扩展") && document.body.innerText.includes("MCP 服务")');
  await until('persistenceTest.calls.some(call => call.cmd === "complete_settings_open" && call.args.requestId === 200 && call.args.error === null)');
  await fresh('main');
  await evaluate(`persistenceTest.failNext('open_settings_window'); document.querySelector('button[title="设置"]').click()`);
  await until('document.querySelector("[data-notification]")?.textContent.includes("打开设置窗口失败")');
  await evaluate(`document.querySelector('[aria-label="关闭通知"]').click()`);
  await until('!document.querySelector("[data-notification]")');
  await evaluate(`persistenceTest.failNext('open_settings_window'); document.querySelector('[data-module-navigation] button[title]').click()`);
  await until('document.querySelector("[data-notification]")?.textContent.includes("打开设置窗口失败")');
  console.log('PASS: settings timeout, retry, late-result isolation, correlated readiness, preserved drafts and visible entry failures');
}, { timeoutMs: 180000 });
